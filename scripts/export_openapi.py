#!/usr/bin/env python3
"""Export the public Latch API contract without loading deployment secrets.

Run with the API virtualenv: python scripts/export_openapi.py [--check].
"""
import argparse
from copy import deepcopy
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from latch_api.app import create_app as vendor_app
from latch_api.device_app import create_app as device_app
from latch_api.documentation import yaml_text
from latch_api.server_app import create_app as server_app


def application_schemas():
    # Factories do not contact dependencies; no app lifespan is started here.
    return [
        (vendor_app().openapi(), {'url': 'http://127.0.0.1:8300',
                                 'description': 'Vendor-data service on the Linux host loopback'}),
        (device_app(object(), 'schema-generation-placeholder-token').openapi(),
         {'url': 'http://device-api:8310',
          'description': 'Optional device access service on Docker service management'}),
        (server_app(object(), 'schema-generation-placeholder-token').openapi(),
         {'url': 'http://server-api:8320',
          'description': 'Server access service on Docker service management'}),
    ]


def combined_schema():
    schemas = application_schemas()
    result = {
        'openapi': schemas[0][0]['openapi'],
        'info': {'title': 'Latch API', 'version': '1.0.0',
                 'description': ('Current vendor-data and access service contracts. Operation-level '
                                 'servers identify the service that hosts each operation. These '
                                 'management listeners are not publicly exposed by the lab.')},
        'paths': {}, 'components': {},
    }
    for schema, server in schemas:
        for section, definitions in schema.get('components', {}).items():
            output = result['components'].setdefault(section, {})
            for name, definition in definitions.items():
                if name in output and output[name] != definition:
                    raise ValueError(f'Conflicting schema component: {section}/{name}')
                output[name] = deepcopy(definition)
        for path, methods in schema['paths'].items():
            output = result['paths'].setdefault(path, {})
            for method, definition in methods.items():
                if method in output:
                    # All services deliberately expose the same liveness shape.
                    if path != '/health/live' or method != 'get':
                        raise ValueError(f'Conflicting operation: {method} {path}')
                    if output[method]['responses'] != definition['responses']:
                        raise ValueError('Conflicting liveness response schema')
                    output[method]['operationId'] = 'latchLiveness'
                    output[method]['tags'] = ['Health']
                    output[method]['servers'].append(server)
                else:
                    output[method] = {**deepcopy(definition), 'servers': [server]}
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if openapi.yaml differs from the apps')
    options = parser.parse_args()
    destination = ROOT / 'openapi.yaml'
    expected = '# Generated by scripts/export_openapi.py; do not edit by hand.\n' + yaml_text(combined_schema())
    if options.check:
        if not destination.exists() or destination.read_text() != expected:
            parser.exit(1, 'openapi.yaml is stale; run scripts/export_openapi.py\n')
        print('openapi.yaml matches the application schemas')
    else:
        destination.write_text(expected)
        print('Wrote openapi.yaml')


if __name__ == '__main__':
    main()
